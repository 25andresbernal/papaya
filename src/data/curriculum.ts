// This file is the big box of Spanish words and lessons for World 1.
// Think of WORDS as a giant box of flashcards. Every card has an id
// (like a label on the card), the Spanish, the English, and an emoji
// picture. UNITS is the map: it groups lessons into 10 topics, and
// each lesson just points at which cards (word ids) it teaches.
//
// Why do lessons only store ids instead of copying the whole word?
// Because some words show up more than once (like "gracias"). If we
// copied the word every time, and we ever fixed a typo, we would have
// to fix it in many places. By keeping ONE card per word and pointing
// at it by id, we only ever have to fix it once. This is called
// "single source of truth" — a fancy way of saying "one true copy".
//
// Some lessons also have `reviewWordIds`. Those are old words from
// earlier lessons mixed back in, so the kid keeps practicing words
// they already learned instead of forgetting them. This is called
// spaced repetition.

